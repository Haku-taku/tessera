//! Generates `Msg` constants from `locales/en/**/*.ftl` and embeds every locale.

use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use fluent_syntax::ast::{Entry, Expression, InlineExpression, Pattern, PatternElement};
use fluent_syntax::parser;

/// One locale: its tag, the files it came from, and its messages.
type Locale = (String, Vec<PathBuf>, Vec<(String, Option<String>, bool)>);

/// One generated message or attribute.
struct Spec {
    id: String,
    attr: Option<String>,
    dynamic: bool,
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let locales_dir = manifest.join("locales");
    println!("cargo:rerun-if-changed=locales");

    let locales = collect_locales(&locales_dir);
    assert!(
        !locales.is_empty(),
        "no locale directories under {}",
        locales_dir.display()
    );

    // Parse every locale once: this rejects syntax errors and duplicate ids at build time.
    let mut parsed: Vec<Locale> = Vec::new();
    let mut endonyms: Vec<(String, String)> = Vec::new();
    for (tag, files) in &locales {
        assert!(!files.is_empty(), "locale {tag} has no .ftl files");
        let mut entries = Vec::new();
        let mut seen = BTreeSet::new();
        let mut name = None;
        for file in files {
            let source =
                fs::read_to_string(file).unwrap_or_else(|e| panic!("read {}: {e}", file.display()));
            let resource = parser::parse_runtime(source.as_str())
                .unwrap_or_else(|(_, errors)| panic!("parse {}: {errors:?}", file.display()));
            for entry in resource.body {
                if let Entry::Message(message) = entry {
                    let id = message.id.name.to_string();
                    if let Some(value) = &message.value {
                        let key = (id.clone(), None);
                        assert!(
                            seen.insert(key.clone()),
                            "duplicate message {key:?} in {tag}"
                        );
                        if id == "language-name" {
                            name = Some(literal(value));
                        }
                        entries.push((id.clone(), None, pattern_dynamic(value)));
                    }
                    for attr in &message.attributes {
                        let attr_name = attr.id.name.to_string();
                        let key = (id.clone(), Some(attr_name.clone()));
                        assert!(
                            seen.insert(key.clone()),
                            "duplicate message {key:?} in {tag}"
                        );
                        entries.push((id.clone(), Some(attr_name), pattern_dynamic(&attr.value)));
                    }
                }
            }
        }
        let name = name.unwrap_or_else(|| {
            panic!("locale {tag} has no plain `language-name` message: a picker needs it")
        });
        endonyms.push((tag.clone(), name));
        parsed.push((tag.clone(), files.clone(), entries));
    }

    let english = parsed
        .iter()
        .find(|(tag, _, _)| tag == "en")
        .expect("locales/en is required: it defines the generated keys");
    let specs: Vec<Spec> = english
        .2
        .iter()
        .map(|(id, attr, dynamic)| Spec {
            id: id.clone(),
            attr: attr.clone(),
            dynamic: *dynamic,
        })
        .collect();
    assert!(!specs.is_empty(), "locales/en defines no messages");
    assert!(
        specs.len() <= u16::MAX as usize,
        "too many messages for Msg(u16)"
    );
    let mut names = BTreeMap::new();
    for spec in &specs {
        assert!(valid_id(&spec.id), "illegal message id {:?}", spec.id);
        if let Some(attr) = &spec.attr {
            assert!(
                valid_id(attr),
                "illegal attribute id {attr:?} on {:?}",
                spec.id
            );
        }
        let name = const_name(spec);
        if let Some(previous) = names.insert(name.clone(), display_name(spec)) {
            panic!(
                "{previous} and {} both generate the constant {name}",
                display_name(spec)
            );
        }
    }

    let mut out = String::new();
    writeln!(out, "// Generated by build.rs; do not edit.").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "/// A message key: an index into the generated table.").unwrap();
    writeln!(out, "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]").unwrap();
    writeln!(out, "pub struct Msg(u16);").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "/// One generated entry: Fluent id, optional attribute, and whether it needs args."
    )
    .unwrap();
    writeln!(out, "#[derive(Clone, Copy, Debug, PartialEq, Eq)]").unwrap();
    writeln!(out, "pub struct MsgSpec {{").unwrap();
    writeln!(out, "    pub id: &'static str,").unwrap();
    writeln!(out, "    pub attr: Option<&'static str>,").unwrap();
    writeln!(out, "    pub dynamic: bool,").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "pub const ALL: &[MsgSpec] = &[").unwrap();
    for spec in &specs {
        let attr = match &spec.attr {
            Some(a) => format!("Some({a:?})"),
            None => "None".to_string(),
        };
        writeln!(
            out,
            "    MsgSpec {{ id: {:?}, attr: {}, dynamic: {} }},",
            spec.id, attr, spec.dynamic
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "impl Msg {{").unwrap();
    writeln!(out, "    /// The table entry this key names.").unwrap();
    writeln!(
        out,
        "    pub fn spec(self) -> &'static MsgSpec {{ &ALL[self.0 as usize] }}"
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "    /// The index this key names.").unwrap();
    writeln!(out, "    pub fn index(self) -> usize {{ self.0 as usize }}").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "    /// The key at `index`, for exhaustive tests over `ALL`."
    )
    .unwrap();
    writeln!(
        out,
        "    pub fn from_index(index: usize) -> Self {{ Msg(index as u16) }}"
    )
    .unwrap();
    for (i, spec) in specs.iter().enumerate() {
        writeln!(out).unwrap();
        writeln!(out, "    pub const {}: Msg = Msg({i});", const_name(spec)).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // Embed each locale's files. The generated file lives in `OUT_DIR`, so the path must be
    // rooted at `CARGO_MANIFEST_DIR`; a relative `include_str!` would resolve against `OUT_DIR`.
    writeln!(out, "/// One locale's concatenated FTL source.").unwrap();
    writeln!(out, "pub struct LocaleFiles {{").unwrap();
    writeln!(out, "    pub tag: &'static str,").unwrap();
    writeln!(out, "    pub source: &'static str,").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "pub const LOCALES: &[LocaleFiles] = &[").unwrap();
    for (tag, files, _) in &parsed {
        let mut parts = Vec::new();
        for file in files {
            let relative = file
                .strip_prefix(&manifest)
                .unwrap_or_else(|_| panic!("{} is outside the manifest", file.display()));
            parts.push(format!(
                "include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {:?}))",
                format!("/{}", relative.to_string_lossy())
            ));
        }
        writeln!(
            out,
            "    LocaleFiles {{ tag: {tag:?}, source: concat!({}) }},",
            parts.join(", \"\\n\", ")
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out).unwrap();

    // Each language names itself, so a picker reads the same in every language.
    writeln!(out, "/// Every shipped locale's endonym, keyed by tag.").unwrap();
    writeln!(out, "pub const LANGUAGE_NAMES: &[(&str, &str)] = &[").unwrap();
    for (tag, name) in &endonyms {
        writeln!(out, "    ({tag:?}, {name:?}),").unwrap();
    }
    writeln!(out, "];").unwrap();

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("out dir"));
    fs::write(out_dir.join("msg.rs"), out).expect("write generated msg.rs");
}

fn display_name(spec: &Spec) -> String {
    match &spec.attr {
        Some(attr) => format!("{}.{}", spec.id, attr),
        None => spec.id.clone(),
    }
}

/// Fluent identifiers: `[a-zA-Z][a-zA-Z0-9_-]*`; dots belong to attributes only.
fn valid_id(id: &str) -> bool {
    let mut chars = id.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    first.is_ascii_alphabetic() && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
}

fn const_name(spec: &Spec) -> String {
    let mut name = spec.id.replace('-', "_").to_uppercase();
    if let Some(attr) = &spec.attr {
        name.push('_');
        name.push_str(&attr.replace('-', "_").to_uppercase());
    }
    name
}

/// Locale directories and their `.ftl` files, both sorted for deterministic output.
fn collect_locales(dir: &Path) -> Vec<(String, Vec<PathBuf>)> {
    let mut locales = Vec::new();
    let entries = fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
    let mut dirs: Vec<PathBuf> = entries
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.is_dir())
        .collect();
    dirs.sort();
    for path in dirs {
        let tag = path.file_name().unwrap().to_string_lossy().to_string();
        let mut files = Vec::new();
        collect_ftl(&path, &mut files);
        files.sort();
        locales.push((tag, files));
    }
    locales
}

fn collect_ftl(dir: &Path, out: &mut Vec<PathBuf>) {
    let entries = fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
    for entry in entries {
        let path = entry.expect("dir entry").path();
        if path.is_dir() {
            collect_ftl(&path, out);
        } else if path.extension().is_some_and(|ext| ext == "ftl") {
            out.push(path);
        }
    }
}

/// Whether a pattern reads any variable, directly or through a nested expression.
/// The text of a message that must be a plain string.
fn literal(pattern: &Pattern<&str>) -> String {
    let mut text = String::new();
    for element in &pattern.elements {
        match element {
            PatternElement::TextElement { value } => text.push_str(value),
            PatternElement::Placeable { .. } => {
                panic!("language-name must be plain text, without placeables")
            }
        }
    }
    text.trim().to_string()
}

fn pattern_dynamic(pattern: &Pattern<&str>) -> bool {
    pattern.elements.iter().any(|element| match element {
        PatternElement::TextElement { .. } => false,
        PatternElement::Placeable { expression } => expression_dynamic(expression),
    })
}

fn expression_dynamic(expression: &Expression<&str>) -> bool {
    match expression {
        Expression::Select { selector, variants } => {
            inline_dynamic(selector)
                || variants
                    .iter()
                    .any(|variant| pattern_dynamic(&variant.value))
        }
        Expression::Inline(inline) => inline_dynamic(inline),
    }
}

fn inline_dynamic(inline: &InlineExpression<&str>) -> bool {
    match inline {
        InlineExpression::VariableReference { .. } => true,
        InlineExpression::FunctionReference { arguments, .. } => {
            arguments.positional.iter().any(inline_dynamic)
                || arguments.named.iter().any(|arg| inline_dynamic(&arg.value))
        }
        InlineExpression::TermReference { arguments, .. } => {
            arguments.as_ref().is_some_and(|arguments| {
                arguments.positional.iter().any(inline_dynamic)
                    || arguments.named.iter().any(|arg| inline_dynamic(&arg.value))
            })
        }
        InlineExpression::Placeable { expression } => expression_dynamic(expression),
        InlineExpression::MessageReference { .. }
        | InlineExpression::StringLiteral { .. }
        | InlineExpression::NumberLiteral { .. } => false,
    }
}
